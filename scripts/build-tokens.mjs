// Turns tokens/tokens.json into CSS custom properties and a typed TS map.
// Primitives become --hb-<path>; semantic tokens become --hb-<name> and reference primitives with var(),
// so a theme switch only swaps the semantic layer.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("../tokens/tokens.json", import.meta.url), "utf8"));
const flat = {};
const walk = (obj, path) => {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("$")) continue;
    if (typeof v === "object") walk(v, [...path, k]);
    else flat[[...path, k].join("-")] = v;
  }
};
walk(tokens.primitive, []);

const ref = (value) =>
  value.replace(/\{([^}]+)\}/g, (_, p) => {
    const name = p.replaceAll(".", "-");
    if (!(name in flat)) throw new Error(`Unknown token reference {${p}}`);
    return `var(--hb-${name})`;
  });

const block = (entries) => entries.map(([k, v]) => `  --hb-${k}: ${v};`).join("\n");
const light = Object.entries(tokens.semantic.light).map(([k, v]) => [k, ref(v)]);
const dark = Object.entries(tokens.semantic.dark).map(([k, v]) => [k, ref(v)]);

for (const key of Object.keys(tokens.semantic.light)) {
  if (!(key in tokens.semantic.dark)) throw new Error(`Dark theme is missing ${key}`);
}

const css = `/* Generated by scripts/build-tokens.mjs. Edit tokens/tokens.json instead. */
:root {
${block(Object.entries(flat))}
${block(light)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(dark).replaceAll("\n  ", "\n    ").replace(/^  /, "    ")}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${block(dark)}
  color-scheme: dark;
}
`;

const ts = `// Generated by scripts/build-tokens.mjs. Edit tokens/tokens.json instead.
export const primitives = ${JSON.stringify(flat, null, 2)} as const;

export const semanticLight = ${JSON.stringify(tokens.semantic.light, null, 2)} as const;

export const semanticDark = ${JSON.stringify(tokens.semantic.dark, null, 2)} as const;

export type SemanticToken = keyof typeof semanticLight;

/** CSS variable for a semantic token, for use in inline styles or other frameworks. */
export const cssVar = (token: SemanticToken) => \`var(--hb-\${token})\`;
`;

mkdirSync(new URL("../src/tokens/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/tokens/tokens.css", import.meta.url), css);
writeFileSync(new URL("../src/tokens/tokens.ts", import.meta.url), ts);
console.log(`tokens: ${Object.keys(flat).length} primitives, ${light.length} semantic (light + dark)`);
